const LanguageContext = createContext(null);

function getInitialLanguage() {
    try {
        return window.localStorage.getItem("maqnet-language") === "en" ? "en" : "id";
    } catch (error) {
        console.error("Unable to read saved language preference:", error);
        return "id";
    }
}

export function LanguageProvider({ children }) {
    const [language, setLanguage] = useState(getInitialLanguage);

    useEffect(() => {
        try {
            window.localStorage.setItem("maqnet-language", language);
        } catch (error) {
            console.error("Unable to save language preference:", error);
        }
    }, [language]);

    const value = useMemo(() => ({
        language,
        setLanguage,
        t: (key, values = {}) => {
            const template = translations[language][key] || translations.id[key] || key;
            return template.replace(/\{(\w+)\}/g, (_, name) => values[name] ?? `{${name}}`);
        }
    }), [language]);

    return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

// This custom hook is intentionally colocated with the provider's context.
// eslint-disable-next-line react-refresh/only-export-components
export function useLanguage() {
    const context = useContext(LanguageContext);
    if (!context) throw new Error("useLanguage must be used within a LanguageProvider");
    return context;
}
